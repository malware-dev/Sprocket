namespace Sprocket.Sim.Blueprints;

/// <summary>A face of a block, as its definition's mount points name it.</summary>
public enum Side
{
    /// <summary>The face toward the block's back.</summary>
    Back,

    /// <summary>The face under the block.</summary>
    Bottom,

    /// <summary>The face toward the block's front.</summary>
    Front,

    /// <summary>The face on the block's left.</summary>
    Left,

    /// <summary>The face on the block's right.</summary>
    Right,

    /// <summary>The face over the block.</summary>
    Top
}
