using System.Collections.Generic;
using System.Text;

namespace Sprocket.Localization.Generator
{
    /// <summary>Writes the class that says a file's texts: one property each.</summary>
    /// <remarks>
    ///     The class it writes is compiled by the game, so it holds to C# 6 and uses nothing a mod may not.
    /// </remarks>
    static class Writer
    {
        /// <summary>The source of class <paramref name="type" /> in <paramref name="space" />, saying <paramref name="texts" /> through the runtime in <paramref name="runtime" />.</summary>
        public static string Write(string space, string type, string runtime, string file, IList<Said> texts)
        {
            var phrase = "global::" + runtime + ".Phrase";
            var book = "global::" + runtime + ".Phrasebook";

            var source = new StringBuilder();
            source.Append("// <auto-generated />\n");
            source.Append("namespace ").Append(space).Append("\n{\n");
            source.Append("    /// <summary>The texts written in ").Append(Xml(file))
                .Append(", each said in the language loaded into <see cref=\"Book\" />.</summary>\n");
            source.Append("    public sealed class ").Append(type).Append("\n    {\n");

            source.Append("        static readonly ").Append(phrase).Append("[] All =\n        {\n");
            for (var i = 0; i < texts.Count; i++)
            {
                source.Append("            new ").Append(phrase).Append("(").Append(i).Append(", ")
                    .Append(Literal(texts[i].Key)).Append(", ").Append(Literal(texts[i].Written)).Append("),\n");
            }

            source.Append("        };\n\n");

            source.Append("        /// <summary>Every text said as written, until <see cref=\"Book\" /> loads a language.</summary>\n");
            source.Append("        public ").Append(type).Append("()\n        {\n");
            source.Append("            Book = new ").Append(book).Append("(All);\n        }\n\n");

            source.Append("        /// <summary>The texts in the language loaded.</summary>\n");
            source.Append("        public ").Append(book).Append(" Book { get; }\n");

            for (var i = 0; i < texts.Count; i++)
            {
                source.Append('\n');
                Summary(source, texts[i]);
                source.Append("        public string ").Append(texts[i].Member)
                    .Append(" => Book.Say(All[").Append(i).Append("]);\n");
            }

            source.Append("    }\n}\n");
            return source.ToString();
        }

        /// <summary>The text as written, and the note beside it, as the property's documentation.</summary>
        static void Summary(StringBuilder source, Said text)
        {
            source.Append("        /// <summary>\n");
            Lines(source, text.Written);
            source.Append("        /// </summary>\n");

            if (string.IsNullOrEmpty(text.Comment))
                return;

            source.Append("        /// <remarks>\n");
            Lines(source, text.Comment);
            source.Append("        /// </remarks>\n");
        }

        static void Lines(StringBuilder source, string text)
        {
            var lines = text.Replace("\r\n", "\n").Split('\n');
            for (var i = 0; i < lines.Length; i++)
            {
                source.Append("        /// ").Append(Xml(lines[i]));
                source.Append(i < lines.Length - 1 ? "<br />\n" : "\n");
            }
        }

        static string Xml(string text)
        {
            return text.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");
        }

        /// <summary><paramref name="text" /> as a C# string literal.</summary>
        static string Literal(string text)
        {
            var literal = new StringBuilder(text.Length + 2);
            literal.Append('"');

            foreach (var c in text)
            {
                switch (c)
                {
                    case '"': literal.Append("\\\""); break;
                    case '\\': literal.Append("\\\\"); break;
                    case '\n': literal.Append("\\n"); break;
                    case '\r': literal.Append("\\r"); break;
                    case '\t': literal.Append("\\t"); break;
                    default:
                        if (c < ' ')
                            literal.Append("\\u").Append(((int)c).ToString("x4"));
                        else
                            literal.Append(c);
                        break;
                }
            }

            return literal.Append('"').ToString();
        }
    }
}
