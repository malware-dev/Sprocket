using System.Collections.Generic;
using System.Text;

namespace Sprocket.Localization.Generator
{
    /// <summary>Writes the class that says a file's texts: one property each.</summary>
    /// <remarks>
    ///     The class it writes is compiled by the game, so it holds to C# 6 and uses nothing a mod may not.
    /// </remarks>
    static class Writer
    {
        /// <summary>
        ///     The source of class <paramref name="type" /> in <paramref name="space" />, saying <paramref name="texts" /> through the
        ///     runtime in <paramref name="runtime" />, and holding one of each class in <paramref name="beside" />, the mod's other
        ///     files of texts, which it loads with its own.
        /// </summary>
        public static string Write(string space, string type, string runtime, string file, IList<Said> texts, IList<string> beside)
        {
            var phrase = "global::" + runtime + ".Phrase";
            var book = "global::" + runtime + ".Phrasebook";
            var source = "global::" + runtime + ".ITextSource";

            var code = new StringBuilder();
            code.Append("// <auto-generated />\n");
            code.Append("namespace ").Append(space).Append("\n{\n");
            code.Append("    /// <summary>The texts written in ").Append(Xml(file))
                .Append(", each said in the language <see cref=\"Load\" /> last read.</summary>\n");
            code.Append("    public sealed class ").Append(type).Append("\n    {\n");

            code.Append("        static readonly ").Append(phrase).Append("[] All =\n        {\n");
            for (var i = 0; i < texts.Count; i++)
            {
                code.Append("            new ").Append(phrase).Append("(").Append(i).Append(", ")
                    .Append(Literal(texts[i].Key)).Append(", ").Append(Literal(texts[i].Written)).Append("),\n");
            }

            code.Append("        };\n\n");

            code.Append("        readonly ").Append(book).Append(" _book = new ").Append(book).Append("(All);\n");

            foreach (var other in beside)
            {
                code.Append("\n        /// <summary>The texts written in the mod's file of ").Append(Xml(other))
                    .Append(", loaded with these.</summary>\n");
                code.Append("        public ").Append(other).Append(' ').Append(other).Append(" { get; } = new ").Append(other).Append("();\n");
            }

            code.Append("\n        /// <summary>Reads every text, and every text of the mod's other files, from <paramref name=\"source\" />, or goes back to them as written where it is null.</summary>\n");
            code.Append("        public void Load(").Append(source).Append(" source)\n        {\n");
            code.Append("            _book.Load(source);\n");
            foreach (var other in beside)
                code.Append("            ").Append(other).Append(".Load(source);\n");
            code.Append("        }\n\n");

            code.Append("        /// <summary>The text keyed <paramref name=\"key\" /> in the language loaded, or null where there is no such text.</summary>\n");
            code.Append("        public string Find(string key)\n        {\n            return _book.Find(key);\n        }\n");

            for (var i = 0; i < texts.Count; i++)
            {
                code.Append('\n');
                Summary(code, texts[i]);
                code.Append("        public string ").Append(texts[i].Member)
                    .Append(" => _book.Say(All[").Append(i).Append("]);\n");
            }

            code.Append("    }\n}\n");
            return code.ToString();
        }

        /// <summary>The text as written, and the note beside it, as the property's documentation.</summary>
        static void Summary(StringBuilder source, Said text)
        {
            source.Append("        /// <summary>\n");
            Lines(source, text.Written);
            source.Append("        /// </summary>\n");

            if (string.IsNullOrEmpty(text.Comment))
                return;

            source.Append("        /// <remarks>\n");
            Lines(source, text.Comment);
            source.Append("        /// </remarks>\n");
        }

        static void Lines(StringBuilder source, string text)
        {
            var lines = text.Replace("\r\n", "\n").Split('\n');
            for (var i = 0; i < lines.Length; i++)
            {
                source.Append("        /// ").Append(Xml(lines[i]));
                source.Append(i < lines.Length - 1 ? "<br />\n" : "\n");
            }
        }

        static string Xml(string text)
        {
            return text.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");
        }

        /// <summary><paramref name="text" /> as a C# string literal.</summary>
        static string Literal(string text)
        {
            var literal = new StringBuilder(text.Length + 2);
            literal.Append('"');

            foreach (var c in text)
            {
                switch (c)
                {
                    case '"': literal.Append("\\\""); break;
                    case '\\': literal.Append("\\\\"); break;
                    case '\n': literal.Append("\\n"); break;
                    case '\r': literal.Append("\\r"); break;
                    case '\t': literal.Append("\\t"); break;
                    default:
                        if (c < ' ')
                            literal.Append("\\u").Append(((int)c).ToString("x4"));
                        else
                            literal.Append(c);
                        break;
                }
            }

            return literal.Append('"').ToString();
        }
    }
}
