namespace Sprocket.Host.SpaceEngineers.Framework.Ui.Look
{
    /// <summary>The room between two things on a screen, one size for each job a gap does.</summary>
    public static class Gaps
    {
        /// <summary>Inside one thing: a heading over what it heads, a description under its name.</summary>
        public const float Within = 4f;

        /// <summary>Between the parts of one item, such as the buttons in a row or a chip beside a name.</summary>
        public const float Parts = 8f;

        /// <summary>Between the items of a list.</summary>
        public const float Items = 16f;

        /// <summary>Between sections, and between groups in a list.</summary>
        public const float Sections = 24f;
    }
}
